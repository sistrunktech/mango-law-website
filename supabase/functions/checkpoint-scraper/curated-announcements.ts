function checkpointTitle(city: string, county: string): string {
  return city.trim().toLowerCase() === county.trim().toLowerCase()
    ? `OVI Checkpoint - ${county} County`
    : `OVI Checkpoint - ${city}, ${county} County`;
}

function buildConfirmedCheckpointSeed(input: ConfirmedCheckpointSeedInput): CuratedAnnouncementSeed {
  const source = CONFIRMED_CHECKPOINT_SOURCES[input.source];
  const cityPart =
    input.locationCity.trim().toLowerCase() === input.locationCounty.trim().toLowerCase()
      ? input.locationCounty
      : input.locationCity;

  return {
    id: input.id,
    title: `${input.locationCounty} County OVI checkpoint announced at ${input.locationText}`,
    checkpointTitle: checkpointTitle(cityPart, input.locationCounty),
    sourceUrl: `${source.sourceUrl}#${input.id}`,
    sourceName: source.sourceName,
    announcementDate: source.announcementDate,
    eventDate: input.eventDate,
    startDate: input.startDate,
    endDate: input.endDate,
    locationText: input.locationText,
    locationCity: input.locationCity,
    locationCounty: input.locationCounty,
    status: 'confirmed',
    rawText: `${source.rawPrefix} Source location: ${input.locationText}, ${cityPart}, ${input.locationCounty} County. Time window: ${input.startDate} to ${input.endDate}.`,
    promoteToCheckpoint: true,
  };
}

